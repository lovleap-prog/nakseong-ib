window.migrateUnit = function (u) {
  var base = window.newUnit(u.grade, u.theme);
  Object.keys(base).forEach(function (k) {
    if (u[k] === undefined) u[k] = base[k];
    else if (base[k] && typeof base[k] === "object" && !Array.isArray(base[k])) {
      Object.keys(base[k]).forEach(function (kk) { if (u[k][kk] === undefined) u[k][kk] = base[k][kk]; });
    }
  });
  (u.lessons || []).forEach(function (l) { if (l.ilp === undefined) l.ilp = ""; });
  (u.rubric || []).forEach(function (r) { if (r.domain === undefined) r.domain = ""; });
  return u;
};

