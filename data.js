window.stageRole = function (model, stage) {
  var c = window.PYP.cycles[model] || window.PYP.cycles["개념 기반 탐구"];
  if (!stage) return "";
  if (c.open.indexOf(stage) >= 0) return "open";
  var i = c.loop.indexOf(stage); if (i >= 0) return ["inv", "org", "gen"][i];
  if (stage === c.deeper) return "deeper";
  if (c.close.indexOf(stage) >= 0) return "close";
  if (stage === c.reflect) return "reflect";
  return "";
};

